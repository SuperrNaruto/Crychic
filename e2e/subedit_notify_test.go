func TestSubscriptionEditScopeAndUpgradeSurviveClosure(t *testing.T) {
	h := subscriptionEditor(t)
	h.tap(alice, editMessage, "起始集")
	h.answer(alice, editMessage, "12")
	h.tap(alice, editMessage, "查看修改")
	h.tap(alice, editMessage, "确认保存")
	h.transfers(breakingBad.file("S02", "E01"))
	noticeCount(h, 0)
	h.transfers(breakingBad.file("S02", "E12"))
	noticeAt(h, arrivalCheck{message: 3, chat: alice, title: "E12 到家啦"})
	if strings.Contains(mustMessage(h, 3).text, "全部到齐") {
		t.Fatal("changing the start episode fabricated a missing episode's arrival")
	}
	h.tap(alice, editMessage, "刷新")
	h.tap(alice, editMessage, "编辑条件")
	h.tap(alice, editMessage, "起始集")
	h.answer(alice, editMessage, "2")
	chooseEditValue(h, "洗版模式", "2")
	h.tap(alice, editMessage, "查看修改")
	h.mp.editResponse(subscriptionEditResponse{readFails: true})
	h.tap(alice, editMessage, "确认保存")
	h.shows(editMessage, "修改已受理，等待读取")
	h.mp.setRoute(subsPath, ok("subscriptions_none.json"))
	h.mp.setRoute(notifySubscription, ok("subscription_none.json"))
	h.restart()
	h.transfers(breakingBad.file("S02", "E02"))
	noticeAt(h, arrivalCheck{message: 4, chat: alice, title: "E02 到家啦"})
	h.transfers(breakingBad.file("S02", "E12"))
	noticeAt(h, arrivalCheck{message: 5, chat: alice, title: "E12 到家啦"})
	h.transfers()
	noticeCount(h, 3)
	assertEditCount(h, 2)
	h.tr.verify(t)
}

func TestSubscriptionEditCannotBeOverwrittenByOlderArrivalRead(t *testing.T) {
	h := subscriptionEditor(t)
	h.tap(alice, editMessage, "起始集")
	h.answer(alice, editMessage, "12")
	h.tap(alice, editMessage, "查看修改")
	h.tap(alice, editMessage, "确认保存")
	h.tap(alice, editMessage, "刷新")
	h.tap(alice, editMessage, "编辑条件")
	h.tap(alice, editMessage, "起始集")
	h.answer(alice, editMessage, "2")
	chooseEditValue(h, "洗版模式", "2")
	h.tap(alice, editMessage, "查看修改")
	held := h.mp.holdSubscriptionRead()
	defer held.allow()
	h.tr.add(">> An arrival poll reads the old start episode before the edit is saved")
	file := breakingBad.file("S02", "E02")
	h.logTransfers([]transfer{file})
	h.mp.add(file)
	h.wait(held.entered, "an old subscription scope read")
	h.tap(alice, editMessage, "确认保存")
	h.mp.setRoute(subsPath, ok("subscriptions_none.json"))
	h.mp.setRoute(notifySubscription, ok("subscription_none.json"))
	h.tr.add(">> The old read returns after the acknowledged edit and row closure")
	held.allow()
	h.wait(held.exited, "the older read returning")
	h.transfers()
	noticeAt(h, arrivalCheck{message: 3, chat: alice, title: "E02 到家啦"})
	h.restart()
	h.transfers(breakingBad.file("S02", "E02"))
	noticeAt(h, arrivalCheck{message: 4, chat: alice, title: "E02 到家啦"})
	noticeCount(h, 2)
	h.tr.verify(t)
}
