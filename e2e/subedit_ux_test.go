func TestSubscriptionEditExitProtectsUnsavedDraft(t *testing.T) {
	h := subscriptionEditor(t)
	chooseEditValue(h, "分辨率", "1")
	h.tap(alice, editMessage, "返回")
	h.shows(editMessage, "放弃未保存修改")
	discard, _ := findButton(mustMessage(h, editMessage).rows, "放弃修改")
	h.tap(bob, editMessage, "放弃修改")
	h.tap(alice, editMessage, "返回")
	h.shows(editMessage, "2160p / 4K")
	h.tap(alice, editMessage, "包含条件")
	h.tap(alice, editMessage, "取消")
	h.shows(editMessage, "放弃未保存修改")
	h.tapData(alice, editMessage, discard)
	h.shows(editMessage, "放弃未保存修改")
	h.tap(alice, editMessage, "返回")
	h.answer(alice, editMessage, "字幕组")
	h.shows(editMessage, "有 2 项未保存")
	h.tap(alice, editMessage, "返回")
	h.tap(alice, editMessage, "放弃修改")
	h.shows(editMessage, "订阅详情")
	h.tap(alice, editMessage, "暂停订阅")
	h.shows(editMessage, "已暂停")
	h.tap(alice, editMessage, "编辑条件")
	h.shows(editMessage, "没有未保存的修改")
	h.tap(alice, editMessage, "返回")
	h.shows(editMessage, "订阅详情")
	h.tap(alice, editMessage, "编辑条件")
	h.tap(alice, editMessage, "包含条件")
	h.answer(alice, editMessage, "字幕组")
	h.tap(alice, editMessage, "取消")
	h.tap(alice, editMessage, "放弃修改")
	h.shows(editMessage, "已取消")
	assertEditCount(h, 0)
	h.tr.verify(t)
}

func TestSubscriptionEditRestoresOneFieldWithoutLosingOthers(t *testing.T) {
	h := subscriptionEditor(t)
	h.tap(alice, editMessage, "分辨率")
	h.shows(editMessage, "当前")
	h.tap(alice, editMessage, "2")
	h.shows(editMessage, "没有未保存的修改")
	h.tap(alice, editMessage, "分辨率")
	h.tap(alice, editMessage, "1")
	h.shows(editMessage, "分辨率（已修改）")
	h.tap(alice, editMessage, "包含条件")
	h.answer(alice, editMessage, "简体|CHS")
	h.tap(alice, editMessage, "分辨率")
	oldRestore, _ := findButton(mustMessage(h, editMessage).rows, "恢复原值")
	h.tap(alice, editMessage, "恢复原值")
	h.shows(editMessage, "有 1 项未保存")
	h.shows(editMessage, "简体|CHS")
	h.tap(alice, editMessage, "包含条件")
	h.tapData(alice, editMessage, oldRestore)
	h.shows(editMessage, "草稿 · 字面关键词 · 简体|CHS")
	h.tap(alice, editMessage, "返回")
	h.tap(alice, editMessage, "查看修改")
	h.tap(alice, editMessage, "确认保存")
	assertEditPatch(h, map[string]any{"id": 1, "include": "简体|CHS"})
	h.tap(alice, editMessage, "核对结果")
	h.shows(editMessage, "包含条件")
	h.shows(editMessage, "已生效")
	assertNoEditSecrets(h)
	h.tr.verify(t)
}

func TestSubscriptionEditChecksEveryChangedFieldWithoutRewriting(t *testing.T) {
	h := subscriptionEditor(t)
	chooseEditValue(h, "分辨率", "1")
	h.tap(alice, editMessage, "包含条件")
	h.answer(alice, editMessage, "简体")
	h.tap(alice, editMessage, "排除条件")
	h.answer(alice, editMessage, "预告")
	h.tap(alice, editMessage, "站点")
	h.tap(alice, editMessage, "2")
	h.tap(alice, editMessage, "完成选择")
	h.tap(alice, editMessage, "查看修改")
	confirm, _ := findButton(mustMessage(h, editMessage).rows, "确认保存")
	h.mp.editResponse(subscriptionEditResponse{status: http.StatusOK, body: `{}`})
	h.tap(alice, editMessage, "确认保存")
	sub := editableBreakingSeason()
	sub["include"], sub["exclude"], sub["sites"] = "简体", "hidden-filter-token", []int{11, 22}
	h.mp.setRoute(subsPath, ok(writeFixture(t, []map[string]any{sub})))
	h.tap(alice, editMessage, "核对结果")
	checkText(h, "分辨率", "仍为原值")
	checkText(h, "包含条件", "已生效")
	checkText(h, "排除条件", "已变为其他值")
	checkText(h, "站点", "已生效")
	h.tapData(alice, editMessage, confirm)
	h.tap(bob, editMessage, "核对结果")
	h.tap(alice, editMessage, "返回")
	h.shows(editMessage, "订阅清单")
	h.tap(alice, editMessage, "1")
	h.tap(alice, editMessage, "核对结果")
	checkText(h, "站点", "已生效")
	h.mp.setRoute(subsPath, route{status: http.StatusServiceUnavailable, fixture: "server_error.json"})
	h.tap(alice, editMessage, "核对结果")
	h.shows(editMessage, "暂时无法确认")
	for _, label := range []string{"确认保存", "查看修改", "编辑条件"} {
		if _, present := findButton(mustMessage(h, editMessage).rows, label); present {
			t.Errorf("read-only check unexpectedly offers %s", label)
		}
	}
	sub["date"] = "2026-10-05 11:00:00"
	h.mp.setRoute(subsPath, ok(writeFixture(t, []map[string]any{sub})))
	h.tap(alice, editMessage, "核对结果")
	h.shows(editMessage, "暂时无法确认")
	assertEditCount(h, 1)
	assertNoEditSecrets(h)
	h.tr.verify(t)
}

func checkText(h *harness, field, result string) {
	h.t.Helper()
	text := mustMessage(h, editMessage).text
	from := strings.Index(text, "<h4>"+field+"</h4>")
	if from < 0 {
		h.t.Fatalf("result check omitted %s", field)
	}
	section, _, _ := strings.Cut(text[from+len("<h4>"+field+"</h4>"):], "<h4>")
	if !strings.Contains(section, result) {
		h.t.Fatalf("%s did not show %s", field, result)
	}
}

func TestSubscriptionEditConflictRechecksLatestSnapshot(t *testing.T) {
	h := subscriptionEditor(t)
	h.tap(alice, editMessage, "起始集")
	h.answer(alice, editMessage, "12")
	chooseEditValue(h, "分辨率", "1")
	h.tap(alice, editMessage, "查看修改")
	sub := editableBreakingSeason()
	sub["resolution"], sub["total_episode"] = "720p", 10
	h.mp.setRoute(subsPath, ok(writeFixture(t, []map[string]any{sub})))
	h.tap(alice, editMessage, "确认保存")
	h.tap(alice, editMessage, "完成处理")
	h.shows(editMessage, "草稿已保留")
	h.tap(alice, editMessage, "1")
	oldKeep, _ := findButton(mustMessage(h, editMessage).rows, "保留草稿")
	h.tap(alice, editMessage, "保留草稿")
	sub["resolution"] = "BluRay"
	h.mp.setRoute(subsPath, ok(writeFixture(t, []map[string]any{sub})))
	h.tap(alice, editMessage, "完成处理")
	h.shows(editMessage, "待选择")
	h.tap(alice, editMessage, "1")
	h.tapData(alice, editMessage, oldKeep)
	h.shows(editMessage, "选择冲突处理方式")
	h.tap(alice, editMessage, "保留草稿")
	h.mp.setRoute(subsPath, route{status: http.StatusServiceUnavailable, fixture: "server_error.json"})
	h.tap(alice, editMessage, "完成处理")
	h.shows(editMessage, "草稿已保留")
	h.mp.setRoute(subsPath, ok(writeFixture(t, []map[string]any{sub})))
	h.tap(alice, editMessage, "完成处理")
	h.shows(editMessage, "有 2 项未保存")
	h.tap(alice, editMessage, "查看修改")
	h.shows(editMessage, "编辑订阅条件")
	h.tap(alice, editMessage, "起始集")
	h.answer(alice, editMessage, "10")
	h.tap(alice, editMessage, "查看修改")
	h.tap(alice, editMessage, "确认保存")
	assertEditPatch(h, map[string]any{"id": 1, "resolution": "4k|2160p|x2160", "start_episode": 10})
	assertEditCount(h, 1)
	h.tr.verify(t)
}

func TestSubscriptionEditConflictKeepsDraftAndRequiresNewConfirmation(t *testing.T) {
	h := subscriptionEditor(t)
	chooseEditValue(h, "分辨率", "1")
	h.tap(alice, editMessage, "包含条件")
	h.answer(alice, editMessage, "中文字幕")
	h.tap(alice, editMessage, "排除条件")
	h.answer(alice, editMessage, "预告")
	h.tap(alice, editMessage, "查看修改")
	stale, _ := findButton(mustMessage(h, editMessage).rows, "确认保存")
	sub := editableBreakingSeason()
	sub["resolution"], sub["exclude"], sub["quality"] = "720p", "hidden-filter-token", "BluRay"
	h.mp.setRoute(subsPath, ok(writeFixture(t, []map[string]any{sub})))
	h.tap(alice, editMessage, "确认保存")
	h.shows(editMessage, "草稿已保留")
	h.shows(editMessage, "中文字幕")
	assertEditCount(h, 0)
	h.tap(alice, editMessage, "1")
	h.tap(alice, editMessage, "保留草稿")
	h.tap(alice, editMessage, "2")
	h.tap(alice, editMessage, "采用后台")
	h.tap(alice, editMessage, "完成处理")
	h.shows(editMessage, "有 2 项未保存")
	h.shows(editMessage, "BluRay")
	h.tap(alice, editMessage, "查看修改")
	h.tapData(alice, editMessage, stale)
	assertEditCount(h, 0)
	h.tap(alice, editMessage, "确认保存")
	assertEditPatch(h, map[string]any{"id": 1, "resolution": "4k|2160p|x2160", "include": "中文字幕"})
	assertNoEditSecrets(h)
	h.tr.verify(t)
}
